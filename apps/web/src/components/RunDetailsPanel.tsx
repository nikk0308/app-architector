function displayRunMode(mode?: string): string {
  if (mode === "commercial") return "GPT";
  if (mode === "hf-open") return "Qwen";
  if (mode === "hybrid") return "Hybrid";
  return "Baseline";
}

function formatDate(value?: string, language: "ua" | "en" = "en"): string {
  if (!value) return "-";
  const date = new Date(value);
  if (Number.isNaN(date.getTime())) return value;
  return `${date.toLocaleString(language === "ua" ? "uk-UA" : "en-GB", {
    timeZone: "UTC",
    year: "numeric",
    month: "2-digit",
    day: "2-digit",
    hour: "2-digit",
    minute: "2-digit",
  })} UTC`;
}

