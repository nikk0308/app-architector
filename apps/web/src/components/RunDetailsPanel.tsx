function formatMs(value?: number): string {
  if (typeof value !== "number") return "-";
  return value < 1000 ? `${value} ms` : `${(value / 1000).toFixed(1)} s`;
}

function buildTreeFromArtifacts(details: GenerationRunDetails): TreeNode[] {
  const existingTree = details.metadata.fileTree;
  if (existingTree?.length) {
    return existingTree;
  }

  const paths = details.artifacts
    .map((artifact) => artifact.path)
    .filter((path) => path && !path.endsWith("/"));
  const folders = new Set<string>();
  for (const path of paths) {
    const parts = path.split("/").filter(Boolean);
    for (let index = 1; index < parts.length; index += 1) {
      folders.add(parts.slice(0, index).join("/"));
    }
  }

  return [
    ...Array.from(folders).map((path) => ({
      path,
      type: "directory" as const,
    })),
    ...paths.map((path) => ({ path, type: "file" as const })),
  ].sort((left, right) => {
    if (left.path === right.path) return 0;
    return left.path.localeCompare(right.path);
  });
}

function artifactSummaries(
  details: GenerationRunDetails,
): GeneratedArtifactSummary[] {
  return details.artifacts.map((artifact) => ({
    path: artifact.path,
    kind: artifact.kind,
    description: artifact.description,
  }));
}

